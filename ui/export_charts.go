// renderDescendantChartPNG renders a descendant chart structure in PNG
func renderDescendantChartPNG(img *image.RGBA, width, height int, people []*store.Person, s *store.Store) {
	if len(people) == 0 {
		return
	}
	
	root := people[0]
	
	// Layout constants
	boxWidth := 160
	boxHeight := 65
	vertSpacing := 90
	horizSpacing := 12
	
	startX := 50 // Start from left with padding to fit wider trees
	startY := 120
	
	// Build tree structure using store
	tree := buildDescendantTreeWithStore(root, s, 4) // 4 generations max
	
	// Set box sizes (root gets wider box)
	rootBoxWidth := 240.0 // Wider for root to avoid truncation
	setBoxSizesPNG(tree, rootBoxWidth, float64(boxWidth), float64(boxHeight), true)
	
	// Calculate positions for all nodes
	calculateDescendantPositionsPNG(tree, float64(startX), float64(startY), float64(vertSpacing), float64(horizSpacing))
	
	// Draw the tree
	drawDescendantTreePNG(img, tree)
}

// setBoxSizesPNG recursively sets box sizes for PNG rendering
func setBoxSizesPNG(node *descendantNode, rootWidth, childWidth, height float64, isRoot bool) {
	if node == nil {
		return
	}
	
	if isRoot {
		node.boxWidth = rootWidth
	} else {
		node.boxWidth = childWidth
	}
	node.boxHeight = height
	
	for _, child := range node.children {
		setBoxSizesPNG(child, rootWidth, childWidth, height, false)
	}
}

// calculateDescendantPositionsPNG calculates positions for PNG rendering
func calculateDescendantPositionsPNG(node *descendantNode, x, y, vertSpacing, horizSpacing float64) float64 {
	if node == nil {
		return x
	}
	
	node.x = x
	node.y = y
	
	if len(node.children) == 0 {
		return x + node.boxWidth + horizSpacing
	}
	
	// Position children below
	childY := y + node.boxHeight + vertSpacing
	childX := x
	
	for _, child := range node.children {
		childX = calculateDescendantPositionsPNG(child, childX, childY, vertSpacing, horizSpacing)
	}
	
	// Center parent above children
	if len(node.children) > 0 {
		firstChildX := node.children[0].x
		lastChildX := node.children[len(node.children)-1].x
		node.x = (firstChildX + lastChildX) / 2
	}
	
	return childX
}

// drawDescendantTreePNG draws the descendant tree in PNG
func drawDescendantTreePNG(img *image.RGBA, node *descendantNode) {
	if node == nil {
		return
	}
	
	// Draw this node using its own box size
	drawPersonBox(img, int(node.x), int(node.y), int(node.boxWidth), int(node.boxHeight), node.person)
	
	// Draw lines to children and recurse
	for _, child := range node.children {
		// Draw line from parent to child
		lineColor := color.RGBA{150, 150, 150, 255}
		parentCenterX := int(node.x + node.boxWidth/2)
		parentBottomY := int(node.y + node.boxHeight)
		childCenterX := int(child.x + child.boxWidth/2)
		childTopY := int(child.y)
		
		// Vertical line from parent
		midY := (parentBottomY + childTopY) / 2
		drawLine(img, parentCenterX, parentBottomY, parentCenterX, midY, lineColor)
		// Horizontal line to child
		if parentCenterX < childCenterX {
			drawLine(img, parentCenterX, midY, childCenterX, midY, lineColor)
		} else {
			drawLine(img, childCenterX, midY, parentCenterX, midY, lineColor)
		}
		// Vertical line to child
		drawLine(img, childCenterX, midY, childCenterX, childTopY, lineColor)
		
		drawDescendantTreePNG(img, child)
	}
}


// drawLine draws a line on an image
func drawLine(img *image.RGBA, x1, y1, x2, y2 int, col color.RGBA) {
	// Simple line drawing using Bresenham's algorithm
	dx := x2 - x1
	if dx < 0 {
		dx = -dx
	}
	dy := y2 - y1
	if dy < 0 {
		dy = -dy
	}
	
	var sx, sy int
	if x1 < x2 {
		sx = 1
	} else {
		sx = -1
	}
	if y1 < y2 {
		sy = 1
	} else {
		sy = -1
	}
	
	err := dx - dy
	
	for {
		img.Set(x1, y1, col)
		
		if x1 == x2 && y1 == y2 {
			break
		}
		
		e2 := 2 * err
		if e2 > -dy {
			err -= dy
			x1 += sx
		}
		if e2 < dx {
			err += dx
			y1 += sy
		}
	}
}

// sanitizeFilename removes characters that aren't safe for filenames
func sanitizeFilename(name string) string {
	// Replace common problematic characters
	name = strings.ReplaceAll(name, "/", "-")
	name = strings.ReplaceAll(name, "\\", "-")
	name = strings.ReplaceAll(name, ":", "-")
	name = strings.ReplaceAll(name, "*", "-")
	name = strings.ReplaceAll(name, "?", "-")
	name = strings.ReplaceAll(name, "\"", "-")
	name = strings.ReplaceAll(name, "<", "-")
	name = strings.ReplaceAll(name, ">", "-")
	name = strings.ReplaceAll(name, "|", "-")
	
	// Replace spaces with underscores
	name = strings.ReplaceAll(name, " ", "_")
	
	// Limit length
	if len(name) > 50 {
		name = name[:50]
	}
	
	return name
}
