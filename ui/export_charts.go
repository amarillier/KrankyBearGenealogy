// addPeopleList adds a formatted list of people to the PDF with boxes
func addPeopleList(pdf *gofpdf.Fpdf, people []*store.Person) {
	// Remove duplicates
	seen := make(map[int64]bool)
	uniquePeople := make([]*store.Person, 0)
	for _, p := range people {
		if p != nil && !seen[p.ID] {
			seen[p.ID] = true
			uniquePeople = append(uniquePeople, p)
		}
	}
	
	// Two-column layout
	leftX := 10.0
	rightX := 150.0
	colWidth := 130.0
	boxHeight := 16.0
	
	for i, person := range uniquePeople {
		if i > 0 && i%30 == 0 { // New page after 30 people
			pdf.AddPage()
			pdf.SetY(20.0)
		}
		
		// Alternate between columns
		x := leftX
		if i%2 == 1 {
			x = rightX
		}
		
		// Move to next row every 2 people
		if i > 0 && i%2 == 0 {
			pdf.Ln(boxHeight + 2)
		}
		
		y := pdf.GetY()
		
		// Draw colored box based on gender
		if person.Gender == "M" {
			pdf.SetFillColor(173, 216, 230) // Light blue
			pdf.SetDrawColor(70, 130, 180)  // Steel blue
		} else if person.Gender == "F" {
			pdf.SetFillColor(255, 192, 203) // Pink
			pdf.SetDrawColor(219, 112, 147) // Pale violet red
		} else {
			pdf.SetFillColor(240, 240, 240) // Light gray
			pdf.SetDrawColor(150, 150, 150) // Gray
		}
		
		pdf.SetLineWidth(0.5)
		pdf.Rect(x, y, colWidth, boxHeight, "FD")
		
		// Add person info inside box
		pdf.SetXY(x+3, y+3)
		pdf.SetFont("Arial", "B", 9)
		pdf.SetTextColor(0, 0, 0)
		
		name := formatPersonName(*person)
		if len(name) > 25 {
			name = name[:22] + "..."
		}
		pdf.Cell(colWidth-6, 5, name)
		
		// Add dates on second line
		dates := formatPersonDates(*person)
		if dates != "" {
			pdf.SetXY(x+3, y+9)
			pdf.SetFont("Arial", "", 7)
			pdf.SetTextColor(60, 60, 60)
			if len(dates) > 32 {
				dates = dates[:29] + "..."
			}
			pdf.Cell(colWidth-6, 4, dates)
		}
		
		pdf.SetTextColor(0, 0, 0)
	}
}

// formatPersonDates formats birth and death dates for display
func formatPersonDates(person store.Person) string {
	var parts []string
	
	if person.BirthDate != "" {
		parts = append(parts, "b. "+person.BirthDate)
	}
	if person.DeathDate != "" {
		parts = append(parts, "d. "+person.DeathDate)
	}
	
	if len(parts) > 0 {
		return strings.Join(parts, ", ")
	}
	return ""
}

// renderPedigreeChartPDF renders an ancestor/pedigree chart in PDF matching the app layout
func renderPedigreeChartPDF(pdf *gofpdf.Fpdf, people []*store.Person, chartTitle string) {
	if len(people) == 0 {
		return
	}
	
	pdf.AddPage()
	pdf.SetY(15)
	
	// Draw title
	pdf.SetFont("Arial", "B", 12)
	pdf.SetTextColor(0, 51, 102)
	if strings.Contains(chartTitle, "Fan") {
		pdf.Cell(0, 8, "Ancestor Chart (Pedigree Format)")
		pdf.Ln(6)
		pdf.SetFont("Arial", "I", 9)
		pdf.SetTextColor(80, 80, 80)
		pdf.Cell(0, 6, "Fan chart ancestors shown in columnar pedigree layout for PDF export")
	} else {
		pdf.Cell(0, 8, "Pedigree Chart")
	}
	pdf.Ln(10)
	pdf.SetTextColor(0, 0, 0)
	
	// Organize people by generation (person[0] is root, then parents, grandparents, etc.)
	root := people[0]
	
	// Layout constants - compact to fit all 4 generations
	boxWidth := 50.0
	boxHeight := 18.0
	colWidth := 58.0  // Reduced spacing between columns
	vertSpacing := 22.0
	startX := 12.0
	startY := 100.0  // Moved down to center the chart vertically
	
	// Draw generation labels
	pdf.SetFont("Arial", "B", 9)
	pdf.SetTextColor(100, 100, 100)
	for gen := 0; gen < 4 && float64(gen)*colWidth+startX < 280; gen++ {
		x := startX + float64(gen)*colWidth
		pdf.SetXY(x, 25)
		if gen == 0 {
			pdf.Cell(colWidth, 5, "1st")
		} else if gen == 1 {
			pdf.Cell(colWidth, 5, "2nd")
		} else if gen == 2 {
			pdf.Cell(colWidth, 5, "3rd")
		} else {
			pdf.Cell(colWidth, 5, "4th")
		}
	}
	pdf.SetTextColor(0, 0, 0)
	
	// Generation 1: Root person (use wider box to avoid name truncation)
	y := startY
	rootBoxWidth := 80.0 // Wider for root person
	drawPDFPersonBox(pdf, startX, y, rootBoxWidth, boxHeight, root)
	
	// Generation 2: Parents (indices 1-2 in Ahnentafel)
	if len(people) > 2 {
		x2 := startX + colWidth
		
		// Father (top) - index 1
		if people[1] != nil {
			yFather := y - vertSpacing
			pdf.SetFont("Arial", "", 7)
			pdf.SetXY(x2-15, yFather-3)
			pdf.Cell(15, 3, "Father:")
			drawPDFPersonBox(pdf, x2, yFather, boxWidth, boxHeight, people[1])
			// No line from root to parents - relationship is obvious from labels
			drawPDFArrow(pdf, x2+boxWidth, yFather+boxHeight/2, x2+colWidth-2, yFather+boxHeight/2)
		}
		
		// Mother (bottom) - index 2
		if people[2] != nil {
			yMother := y + vertSpacing
			pdf.SetFont("Arial", "", 7)
			pdf.SetXY(x2-15, yMother-3)
			pdf.Cell(15, 3, "Mother:")
			drawPDFPersonBox(pdf, x2, yMother, boxWidth, boxHeight, people[2])
			// No line from root to parents - relationship is obvious from labels
			drawPDFArrow(pdf, x2+boxWidth, yMother+boxHeight/2, x2+colWidth-2, yMother+boxHeight/2)
		}
	}
	
	// Generation 3: Grandparents (indices 3-6 in Ahnentafel)
	// Ahnentafel: 3=paternal grandfather, 4=paternal grandmother, 5=maternal grandfather, 6=maternal grandmother
	if len(people) > 6 {
		x3 := startX + 2*colWidth
		yFather := y - vertSpacing // Father's Y position
		yMother := y + vertSpacing // Mother's Y position
		
		// Paternal grandparents (father's parents) - indices 3 and 4
		// Paternal grandfather (index 3) - top of father's line
		if people[3] != nil {
			yPG := yFather - vertSpacing/2
			drawPDFPersonBox(pdf, x3, yPG, boxWidth, boxHeight, people[3])
			drawPDFArrow(pdf, x3+boxWidth, yPG+boxHeight/2, x3+colWidth-2, yPG+boxHeight/2)
		}
		
		// Paternal grandmother (index 4) - bottom of father's line
		if people[4] != nil {
			yPGM := yFather + vertSpacing/2
			drawPDFPersonBox(pdf, x3, yPGM, boxWidth, boxHeight, people[4])
			drawPDFArrow(pdf, x3+boxWidth, yPGM+boxHeight/2, x3+colWidth-2, yPGM+boxHeight/2)
		}
		
		// Maternal grandparents (mother's parents) - indices 5 and 6
		// Maternal grandfather (index 5) - top of mother's line
		if people[5] != nil {
			yMG := yMother - vertSpacing/2
			drawPDFPersonBox(pdf, x3, yMG, boxWidth, boxHeight, people[5])
			drawPDFArrow(pdf, x3+boxWidth, yMG+boxHeight/2, x3+colWidth-2, yMG+boxHeight/2)
		}
		
		// Maternal grandmother (index 6) - bottom of mother's line
		if people[6] != nil {
			yMGM := yMother + vertSpacing/2
			drawPDFPersonBox(pdf, x3, yMGM, boxWidth, boxHeight, people[6])
			drawPDFArrow(pdf, x3+boxWidth, yMGM+boxHeight/2, x3+colWidth-2, yMGM+boxHeight/2)
		}
	}
	
	// Generation 4: Great-grandparents (indices 7-14 in Ahnentafel)
	// 7-8: parents of person 3, 9-10: parents of person 4, 11-12: parents of person 5, 13-14: parents of person 6
	if len(people) > 7 {
		x4 := startX + 3*colWidth
		yFather := y - vertSpacing  // Father's Y position (gen 2)
		yMother := y + vertSpacing  // Mother's Y position (gen 2)
		smallSpacing := vertSpacing / 4
		
		// Calculate grandparent Y positions (gen 3)
		yPG := yFather - vertSpacing/2   // Paternal grandfather (person 3)
		yPGM := yFather + vertSpacing/2  // Paternal grandmother (person 4)
		yMG := yMother - vertSpacing/2   // Maternal grandfather (person 5)
		yMGM := yMother + vertSpacing/2  // Maternal grandmother (person 6)
		
		// Parents of paternal grandfather (person 3) - indices 7, 8
		// These should align with person 3's Y position (yPG)
		if len(people) > 7 && people[7] != nil {
			yGGF1 := yPG - smallSpacing
			if yGGF1 > 15 && yGGF1+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGF1, boxWidth, boxHeight, people[7])
			}
		}
		if len(people) > 8 && people[8] != nil {
			yGGM1 := yPG + smallSpacing
			if yGGM1 > 15 && yGGM1+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGM1, boxWidth, boxHeight, people[8])
			}
		}
		
		// Parents of paternal grandmother (person 4) - indices 9, 10
		// These should align with person 4's Y position (yPGM)
		if len(people) > 9 && people[9] != nil {
			yGGF2 := yPGM - smallSpacing
			if yGGF2 > 15 && yGGF2+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGF2, boxWidth, boxHeight, people[9])
			}
		}
		if len(people) > 10 && people[10] != nil {
			yGGM2 := yPGM + smallSpacing
			if yGGM2 > 15 && yGGM2+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGM2, boxWidth, boxHeight, people[10])
			}
		}
		
		// Parents of maternal grandfather (person 5) - indices 11, 12
		// These should align with person 5's Y position (yMG)
		if len(people) > 11 && people[11] != nil {
			yGGF3 := yMG - smallSpacing
			if yGGF3 > 15 && yGGF3+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGF3, boxWidth, boxHeight, people[11])
			}
		}
		if len(people) > 12 && people[12] != nil {
			yGGM3 := yMG + smallSpacing
			if yGGM3 > 15 && yGGM3+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGM3, boxWidth, boxHeight, people[12])
			}
		}
		
		// Parents of maternal grandmother (person 6) - indices 13, 14
		// These should align with person 6's Y position (yMGM)
		if len(people) > 13 && people[13] != nil {
			yGGF4 := yMGM - smallSpacing
			if yGGF4 > 15 && yGGF4+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGF4, boxWidth, boxHeight, people[13])
			}
		}
		if len(people) > 14 && people[14] != nil {
			yGGM4 := yMGM + smallSpacing
			if yGGM4 > 15 && yGGM4+boxHeight < 190 {
				drawPDFPersonBox(pdf, x4, yGGM4, boxWidth, boxHeight, people[14])
			}
		}
	}
	
	// Add footer note
	pdf.SetY(190)
	pdf.SetFont("Arial", "I", 8)
	pdf.SetTextColor(100, 100, 100)
	pdf.MultiCell(0, 4, "For Full Visual Experience: Open this chart in KrankyBear Genealogy to see\ninteractive boxes, colors, zoom controls, and navigation features.", "", "C", false)
}

// drawPDFArrow draws a simple arrow line in PDF
func drawPDFArrow(pdf *gofpdf.Fpdf, x1, y1, x2, y2 float64) {
	pdf.SetDrawColor(180, 180, 180)
	pdf.SetLineWidth(0.3)
	pdf.Line(x1, y1, x2, y2)
}

// descendantNode represents a person in the descendant tree with their children
type descendantNode struct {
	person    *store.Person
	children  []*descendantNode
	x, y      float64 // Calculated position
	boxWidth  float64 // Box width (wider for root)
	boxHeight float64 // Box height
}

// renderDescendantChartPDF renders a descendant chart in PDF
func renderDescendantChartPDF(pdf *gofpdf.Fpdf, people []*store.Person, s *store.Store) {
	if len(people) == 0 {
		return
	}
	
	pdf.AddPage()
	pdf.SetY(20)
	
	root := people[0]
	
	// Draw chart title
	pdf.SetFont("Arial", "B", 14)
	pdf.Cell(0, 10, "Descendant Chart Structure")
	pdf.Ln(12)
	
	boxWidth := 50.0
	boxHeight := 16.0
	vertSpacing := 25.0
	horizSpacing := 5.0
	
	startX := 15.0 // Start from left to fit wider trees
	startY := 50.0
	
	// Build tree structure from flat list using store
	tree := buildDescendantTreeWithStore(root, s, 4) // 4 generations max
	
	// Set box sizes (root gets wider box)
	rootBoxWidth := 80.0 // Wider for root to avoid truncation
	setBoxSizesPDF(tree, rootBoxWidth, boxWidth, boxHeight, true)
	
	// Calculate positions for all nodes
	calculateDescendantPositions(tree, startX, startY, vertSpacing, horizSpacing)
	
	// Draw the tree
	drawDescendantTreePDF(pdf, tree)
	
	// Add note
	pdf.SetY(240)
	pdf.SetFont("Arial", "I", 9)
	pdf.SetTextColor(100, 100, 100)
	pdf.MultiCell(0, 5, "Note: For the complete interactive chart with all descendants,\nexpanding branches, and navigation features, open in KrankyBear Genealogy application.", "", "L", false)
}

// buildDescendantTreeWithStore builds a proper tree structure using store queries
func buildDescendantTreeWithStore(root *store.Person, s *store.Store, maxGen int) *descendantNode {
	if root == nil || s == nil {
		return nil
	}
	
	return buildDescendantNodeRecursive(root, s, 1, maxGen)
}

// setBoxSizesPDF recursively sets box sizes for PDF rendering
func setBoxSizesPDF(node *descendantNode, rootWidth, childWidth, height float64, isRoot bool) {
	if node == nil {
		return
	}
	
	if isRoot {
		node.boxWidth = rootWidth
	} else {
		node.boxWidth = childWidth
	}
	node.boxHeight = height
	
	for _, child := range node.children {
		setBoxSizesPDF(child, rootWidth, childWidth, height, false)
	}
}

// buildDescendantNodeRecursive recursively builds descendant tree
func buildDescendantNodeRecursive(person *store.Person, s *store.Store, currentGen, maxGen int) *descendantNode {
	if person == nil || currentGen > maxGen {
		return nil
	}
	
	node := &descendantNode{
		person:   person,
		children: []*descendantNode{},
	}
	
	// Get children from store
	children, err := s.GetRelatedPeople(person.ID, "child")
	if err == nil && len(children) > 0 {
		for i := range children {
			childNode := buildDescendantNodeRecursive(&children[i], s, currentGen+1, maxGen)
			if childNode != nil {
				node.children = append(node.children, childNode)
			}
		}
	}
	
	return node
}

// calculateDescendantPositions calculates x,y positions for all nodes in the tree
func calculateDescendantPositions(node *descendantNode, x, y, vertSpacing, horizSpacing float64) float64 {
	if node == nil {
		return x
	}
	
	node.x = x
	node.y = y
	
	if len(node.children) == 0 {
		return x + node.boxWidth + horizSpacing
	}
	
	// Position children below
	childY := y + node.boxHeight + vertSpacing
	childX := x
	
	for _, child := range node.children {
		childX = calculateDescendantPositions(child, childX, childY, vertSpacing, horizSpacing)
	}
	
	// Center parent above children
	if len(node.children) > 0 {
		firstChildX := node.children[0].x
		lastChildX := node.children[len(node.children)-1].x
		node.x = (firstChildX + lastChildX) / 2
	}
	
	return childX
}

// drawDescendantTreePDF draws the descendant tree in PDF
func drawDescendantTreePDF(pdf *gofpdf.Fpdf, node *descendantNode) {
	if node == nil {
		return
	}
	
	// Draw this node using its own box size
	drawPDFPersonBox(pdf, node.x, node.y, node.boxWidth, node.boxHeight, node.person)
	
	// Draw lines to children and recurse
	for _, child := range node.children {
		// Draw line from parent to child
		pdf.SetDrawColor(150, 150, 150)
		pdf.SetLineWidth(0.3)
		parentCenterX := node.x + node.boxWidth/2
		parentBottomY := node.y + node.boxHeight
		childCenterX := child.x + child.boxWidth/2
		childTopY := child.y
		
		// Vertical line from parent
		midY := (parentBottomY + childTopY) / 2
		pdf.Line(parentCenterX, parentBottomY, parentCenterX, midY)
		// Horizontal line to child
		pdf.Line(parentCenterX, midY, childCenterX, midY)
		// Vertical line to child
		pdf.Line(childCenterX, midY, childCenterX, childTopY)
		
		drawDescendantTreePDF(pdf, child)
	}
}

