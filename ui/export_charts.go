// showChartExportDialogInternal is the internal implementation
func showChartExportDialogInternal(w fyne.Window, title string, content fyne.CanvasObject, people []*store.Person, s *store.Store) {
	formatSelect := widget.NewSelect([]string{"PDF", "PNG"}, func(string) {})
	formatSelect.SetSelected("PDF")
	
	description := widget.NewLabel(fmt.Sprintf("Export %s", title))
	description.Wrapping = fyne.TextWrapWord
	
	contentBox := container.NewVBox(
		description,
		widget.NewSeparator(),
		widget.NewLabel("Export Format:"),
		formatSelect,
		widget.NewLabel("\nThe file will be saved with the appropriate extension (.pdf or .png)"),
	)
	
	dialog.ShowCustomConfirm("Export Chart", "Export", "Cancel", contentBox, func(export bool) {
		if !export {
			return
		}
		
		format := formatSelect.Selected
		if format == "" {
			dialog.ShowInformation("Format Required", "Please select an export format.", w)
			return
		}
		
		// Determine default extension
		defaultExt := ".pdf"
		if format == "PNG" {
			defaultExt = ".png"
		}
		
		// Generate default filename with timestamp
		timestamp := time.Now().Format("2006-01-02_150405")
		defaultFilename := fmt.Sprintf("%s_%s%s", sanitizeFilename(title), timestamp, defaultExt)
		
		// Show file save dialog with default filename
		saveDialog := dialog.NewFileSave(func(writer fyne.URIWriteCloser, err error) {
			if err != nil {
				dialog.ShowError(err, w)
				return
			}
			if writer == nil {
				return
			}
			
			path := writer.URI().Path()
			originalPath := path
			
			// Close the writer first (it creates an empty file)
			writer.Close()
			
			// Ensure correct extension
			correctPath := path
			if format == "PDF" && filepath.Ext(path) != ".pdf" {
				correctPath = path + ".pdf"
			} else if format == "PNG" && filepath.Ext(path) != ".png" {
				correctPath = path + ".png"
			}
			
			// Remove the empty file if path changed
			if correctPath != originalPath {
				os.Remove(originalPath)
			}
			
			var exportErr error
			if format == "PDF" {
				exportErr = exportChartToPDF(correctPath, title, content, people, s)
			} else {
				exportErr = exportChartToPNG(correctPath, title, content, people, s)
			}
			
			if exportErr != nil {
				dialog.ShowError(fmt.Errorf("Export failed: %v", exportErr), w)
				return
			}
			
			dialog.ShowInformation("Export Complete", fmt.Sprintf("Chart exported successfully to:\n%s", correctPath), w)
		}, w)
		
		// Set default filename
		saveDialog.SetFileName(defaultFilename)
		saveDialog.Show()
	}, w)
}

// exportChartToPDF exports a chart to PDF format
func exportChartToPDF(path string, title string, content fyne.CanvasObject, people []*store.Person, s *store.Store) error {
	// Use landscape for charts
	pdf := gofpdf.New("L", "mm", "A4", "")
	pdf.SetAutoPageBreak(true, 15)
	pdf.AddPage()
	
	// Header with title
	pdf.SetFont("Arial", "B", 20)
	pdf.SetTextColor(0, 51, 102)
	pdf.Cell(0, 12, title)
	pdf.Ln(12)
	
	// Subtitle with export date
	pdf.SetFont("Arial", "", 10)
	pdf.SetTextColor(100, 100, 100)
	pdf.Cell(0, 6, fmt.Sprintf("Generated by KrankyBear Genealogy on %s", time.Now().Format("Monday, January 2, 2006 at 3:04 PM")))
	pdf.Ln(10)
	pdf.SetTextColor(0, 0, 0)
	
	// Draw horizontal line
	pdf.SetDrawColor(200, 200, 200)
	pdf.SetLineWidth(0.5)
	pdf.Line(10, pdf.GetY(), 287, pdf.GetY())
	pdf.Ln(8)
	
	// Chart information section
	pdf.SetFont("Arial", "B", 14)
	pdf.Cell(0, 8, "Chart Overview:")
	pdf.Ln(10)
	
	pdf.SetFont("Arial", "", 11)
	info := extractChartInfo(content, people)
	pdf.MultiCell(0, 6, info, "", "", false)
	pdf.Ln(8)
	
	// Determine chart type from title and render appropriate structure
	if strings.Contains(title, "Pedigree") || strings.Contains(title, "Fan") {
		// Fan charts show same ancestor data, rendered in pedigree columnar layout for PDF
		renderPedigreeChartPDF(pdf, people, title)
	} else if strings.Contains(title, "Descendant") {
		renderDescendantChartPDF(pdf, people, s)
	} else {
		// Fallback: simple list
		if len(people) > 0 {
			pdf.SetFont("Arial", "B", 12)
			pdf.Cell(0, 8, fmt.Sprintf("People in Chart (%d individuals):", len(people)))
			pdf.Ln(8)
			pdf.SetFont("Arial", "", 10)
			addPeopleList(pdf, people)
		}
	}
	
	// Visual representation note
	pdf.SetFillColor(240, 248, 255)
	pdf.Rect(10, pdf.GetY(), 277, 30, "F")
	pdf.SetFont("Arial", "B", 12)
	pdf.SetTextColor(0, 51, 102)
	pdf.Cell(0, 10, "")
	pdf.Ln(6)
	pdf.Cell(0, 6, "For Full Visual Experience:")
	pdf.Ln(7)
	pdf.SetFont("Arial", "", 10)
	pdf.SetTextColor(0, 0, 0)
	pdf.Cell(0, 6, "Open this chart in KrankyBear Genealogy to see interactive boxes, colors, zoom controls, and navigation features.")
	pdf.Ln(8)
	
	// Footer
	pdf.SetY(-20)
	pdf.SetFont("Arial", "I", 8)
	pdf.SetTextColor(128, 128, 128)
	pdf.CellFormat(0, 10, fmt.Sprintf("Page %d", pdf.PageNo()), "", 0, "C", false, 0, "")
	
	return pdf.OutputFileAndClose(path)
}

