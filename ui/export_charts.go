// exportChartToPNG exports a chart to PNG format
func exportChartToPNG(path string, title string, content fyne.CanvasObject, people []*store.Person, s *store.Store) error {
	// Calculate image size based on content
	size := content.Size()
	width := int(size.Width)
	height := int(size.Height)
	
	// Ensure minimum size for proper chart layout
	if width < 1400 {
		width = 1400
	}
	if height < 950 {
		height = 950
	}
	
	// Create an image with light gray background
	img := image.NewRGBA(image.Rect(0, 0, width, height))
	bgColor := color.RGBA{245, 245, 250, 255}
	draw.Draw(img, img.Bounds(), &image.Uniform{bgColor}, image.Point{}, draw.Src)
	
	// Draw title bar
	drawTitleBar(img, width, title)
	
	// Render chart based on type
	if strings.Contains(title, "Pedigree") || strings.Contains(title, "Fan") {
		renderPedigreeChartPNG(img, width, height, people)
	} else if strings.Contains(title, "Descendant") {
		renderDescendantChartPNG(img, width, height, people, s)
	} else {
		// Fallback to grid
		drawPersonBoxes(img, width, height, people)
	}
	
	// Draw chart info footer
	drawChartFooter(img, width, height, len(people))
	
	// Save to file
	file, err := os.Create(path)
	if err != nil {
		return err
	}
	defer file.Close()
	
	return png.Encode(file, img)
}

